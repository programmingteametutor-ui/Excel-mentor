export function conceptName(id: ConceptId): string {
  return CONCEPTS[id]?.name ?? id
}

/** All prerequisites (transitively). */
export function allPrereqs(id: ConceptId, seen = new Set<ConceptId>()): Set<ConceptId> {
  for (const p of CONCEPTS[id]?.prereqs ?? []) {
    if (seen.has(p)) continue
    seen.add(p)
    allPrereqs(p, seen)
  }
  return seen
}

/** Functions any of the given concepts allow (plus harmless helpers). */
export function allowedFunctions(concepts: ConceptId[]): Set<string> {
  const s = new Set<string>(['SUM', 'ROUND', 'ABS'])
  for (const c of concepts) for (const k of [c, ...allPrereqs(c)]) for (const f of CONCEPTS[k]?.functions ?? []) s.add(f)
  return s
}
